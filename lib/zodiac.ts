function hashSeed(s: string): number {
  let h = 0;
  for (let i = 0; i < s.length; i++) {
    h = (h << 5) - h + s.charCodeAt(i);
    h |= 0;
  }
  return Math.abs(h);
}

export function buildZodiacDay(signId: ZodiacSign, date: string): ZodiacDay {
  const sign = ZODIAC_SIGNS.find((s) => s.id === signId)!;
  const seed = hashSeed(`${signId}:${date}`);

  return {
    signId,
    signNameTh: sign.nameTh,
    signSymbol: sign.symbol,
    range: sign.range,
    date,
    overview: OVERVIEWS[seed % OVERVIEWS.length]!,
    love: LOVE[(seed >> 3) % LOVE.length]!,
    career: CAREER[(seed >> 5) % CAREER.length]!,
    finance: FINANCE[(seed >> 7) % FINANCE.length]!,
    health: HEALTH[(seed >> 9) % HEALTH.length]!,
    lucky: {
      number: (seed % 99) + 1,
      color: COLORS[(seed >> 11) % COLORS.length]!.hex,
      colorTh: COLORS[(seed >> 11) % COLORS.length]!.name,
    },
  };
}
